  function getSavedLanguage() {
    try {
      var saved = localStorage.getItem('cockpit_drone_lang');
      if (saved && translations[saved]) {
        return saved;
      }
    } catch(e) {}
    return 'pt-BR';
  }

  function applyLanguage(lang) {
    if (!translations[lang]) {
      lang = 'pt-BR';
    }
    document.documentElement.lang = lang;
    if (lang === 'ar') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }

    var dict = translations[lang];
    var fallback = translations['pt-BR'];

    var elements = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < elements.length; i++) {
      var el = elements[i];
      var key = el.getAttribute('data-i18n');
      var val = dict[key] || fallback[key];
      if (val !== undefined) {
        if (val.indexOf('<') !== -1) {
          el.innerHTML = val;
        } else {
          el.textContent = val;
        }
      }
    }

    var selects = document.querySelectorAll('#lang-select, .lang-select');
    for (var j = 0; j < selects.length; j++) {
      selects[j].value = lang;
    }

    try {
      localStorage.setItem('cockpit_drone_lang', lang);
    } catch(e) {}
  }

  window.changeLanguage = function(lang) {
    applyLanguage(lang);
  };

  window.t = function(key) {
    var lang = getSavedLanguage();
    var dict = translations[lang] || translations['pt-BR'];
    return dict[key] || translations['pt-BR'][key] || key;
  };

  document.addEventListener('DOMContentLoaded', function() {
    var initialLang = getSavedLanguage();
    applyLanguage(initialLang);
  });
